"""Read-only mock of the NSIF service plus extension endpoints, for API Gateway (HTTP API v2).

All routes live under /api/v1. The NSIF routes port the logic of
services/nsif/api/routes.py (UA-AI2S/undergraduate-research-recommender) to in-memory lists.
Extension routes (courses, departments, programs, faculty, matches) do NOT exist in the NSIF
service; they back the CatCloud prototype screens.

Data (generated by mock/generate/*.py, bundled next to this file):
    data/dataset.json  - synthetic students + real courses/departments/programs
    data/faculty.json  - real scraped researchers + synthetic (inferred) projects
"""

import json
import re
from pathlib import Path

DATA = Path(__file__).parent / "data"
_ds = json.loads((DATA / "dataset.json").read_text())
_fac = json.loads((DATA / "faculty.json").read_text())

STUDENTS = _ds["students"]
ENROLLMENTS = _ds["enrollments"]
COURSES = _ds["courses"]
DEPARTMENTS = _ds["departments"]
PROGRAMS = _ds["programs"]
PERSONAS = _ds.get("personas", [])
FACULTY = _fac["faculty"]
FACULTY_BY_ID = {f["faculty_id"]: f for f in FACULTY}
PERSONA_BY_SID = {p["student_id"]: p for p in PERSONAS}

# Mirrors services/nsif/config.py
CAREER_COLUMNS = [
    "career_unsure", "career_arts", "career_business", "career_data", "career_educ",
    "career_engineering", "career_enviro", "career_global", "career_health",
    "career_law", "career_research", "career_notlisted",
]
EXP_STATS_COLUMNS = [  # _compute_stats omits the F21-only exp_employment / exp_coop
    "exp_internship", "exp_networking", "exp_precept", "exp_facresearch", "exp_empresearch",
    "exp_teaching", "exp_studyabroad", "exp_sigproject", "exp_leadership", "exp_skills",
    "exp_service", "exp_other", "exp_none",
]
SEASON_ORDER = {"Fall": 0, "Spring": 1}  # real API sorts season as a string: "Fall" < "Spring"


class ApiError(Exception):
    def __init__(self, status, detail):
        self.status, self.detail = status, detail


def _term_key(r):
    return (r["term_year"] or 0, SEASON_ORDER.get(r["term_season"], -1))


def _latest(records):
    return max(records, key=_term_key) if records else None


def _page_args(q, default_size=20, max_size=100):
    try:
        page = int(q.get("page", 1))
        size = int(q.get("page_size", default_size))
    except ValueError:
        raise ApiError(422, "page and page_size must be integers")
    if page < 1 or not 1 <= size <= max_size:
        raise ApiError(422, f"page must be >= 1 and page_size between 1 and {max_size}")
    return page, size


def _paginate(items, page, size):
    return items[(page - 1) * size: page * size]


# ----------------------------------------------------------------------------- NSIF routes
def health(**_):
    return {"status": "ok", "total_students": len(STUDENTS),
            "total_terms": len({s["term"] for s in STUDENTS})}


def terms(**_):
    seen = {}
    for s in STUDENTS:
        k = (s["term"], s["term_year"], s["term_season"])
        seen[k] = seen.get(k, 0) + 1
    rows = sorted(seen.items(), key=lambda kv: (kv[0][1], SEASON_ORDER.get(kv[0][2], -1)))
    return {"terms": [{"term": t, "term_year": y, "term_season": se, "count": c}
                      for (t, y, se), c in rows]}


def _stats(records, term=None):
    term_counts = {term: len(records)} if term else {}
    if not term:
        for s in STUDENTS:
            term_counts[s["term"]] = term_counts.get(s["term"], 0) + 1
    colleges, career, exp, domains = {}, {}, {}, {}
    for s in records:
        if s["college"]:
            colleges[s["college"]] = colleges.get(s["college"], 0) + 1
        for c in s["career_interests"]:
            if c in CAREER_COLUMNS:
                career[c] = career.get(c, 0) + 1
        for e in s["experience_preferences"]:
            if e in EXP_STATS_COLUMNS:
                exp[e] = exp.get(e, 0) + 1
        for d in s["research_domains"]:
            domains[d] = domains.get(d, 0) + 1
    return {"total_students": len(records), "terms": term_counts, "colleges": colleges,
            "career_interests": career, "experience_preferences": exp, "research_domains": domains}


def stats(**_):
    return _stats(STUDENTS)


def stats_by_term(term, **_):
    return _stats([s for s in STUDENTS if s["term"] == term], term=term)


def _short_college(name):
    if not name:
        return ""
    return (name.replace("College of ", "").replace("Coll of ", "")
            .replace("Ag Life & Env Sci", "CALES").replace("Eller College of Management", "Eller"))


def _demo_student(s, persona=None):
    name = f"{s['first_name']} {s['last_name']}" if s["first_name"] and s["last_name"] else (
        s["full_name"] or s["student_id"])
    label = f"{name} - {s['plan'] or 'Undeclared'} - {_short_college(s['college'])} ({s['term']})"
    out = {"student_id": s["student_id"], "net_id": s["net_id"], "display_label": label,
           "first_name": s["first_name"], "last_name": s["last_name"], "college": s["college"],
           "plan": s["plan"], "term": s["term"]}
    if persona:  # additive fields for the CatCloud student selector (not in the real model)
        out["persona_label"] = persona["label"]
        out["class_standing"] = persona["class_standing"]
    return out


def demo_sample(query, **_):
    try:
        count = int(query.get("count", 100))
    except ValueError:
        raise ApiError(422, "count must be an integer")
    total = len(STUDENTS)
    recent = sorted({(s["term_year"], SEASON_ORDER[s["term_season"]], s["term"]) for s in STUDENTS},
                    reverse=True)[:3]
    terms_ = {t for _, _, t in recent}
    pool = [s for s in STUDENTS if s["term"] in terms_ and s["college"] and s["first_name"]]
    persona_recs = [s for s in pool if s["student_id"] in PERSONA_BY_SID]
    rest = [s for s in pool if s["student_id"] not in PERSONA_BY_SID]
    by_college = {}
    for s in rest:
        by_college.setdefault(s["college"], []).append(s)
    selected, total_pool = [], len(rest) or 1
    for college, rows in by_college.items():
        n = max(1, round(count * len(rows) / total_pool))
        rows = sorted(rows, key=lambda s: (
            "career_research" not in s["career_interests"],
            "exp_facresearch" not in s["experience_preferences"], s["last_name"] or ""))
        selected.extend(rows[:n])
    selected = selected[: max(0, count - len(persona_recs))]
    personas_out = [_demo_student(s, PERSONA_BY_SID[s["student_id"]]) for s in persona_recs]
    personas_out.sort(key=lambda d: d["persona_label"])
    rest_out = sorted((_demo_student(s) for s in selected), key=lambda d: d["display_label"])
    return {"students": personas_out + rest_out, "total_in_db": total}


def get_student(student_id, **_):
    recs = [s for s in STUDENTS if s["student_id"] == student_id]
    if not recs:
        raise ApiError(404, "Student not found")
    return _latest(recs)


def student_history(student_id, **_):
    recs = sorted((s for s in STUDENTS if s["student_id"] == student_id), key=_term_key, reverse=True)
    if not recs:
        raise ApiError(404, "Student not found")
    return recs


def student_by_netid(net_id, **_):
    recs = [s for s in STUDENTS if s["net_id"] == net_id]
    if not recs:
        raise ApiError(404, "Student not found")
    return _latest(recs)


def _validate_search_body(body):
    errs = []
    if not isinstance(body, dict):
        raise ApiError(422, [{"type": "model_attributes_type", "loc": ["body"],
                              "msg": "Input should be a valid dictionary", "input": body}])
    for f in ("career_interests", "experience_preferences", "research_domains"):
        v = body.get(f, [])
        if not isinstance(v, list) or not all(isinstance(x, str) for x in v):
            errs.append({"type": "list_type", "loc": ["body", f],
                         "msg": "Input should be a valid list of strings", "input": v})
    for f in ("term", "college"):
        v = body.get(f)
        if v is not None and not isinstance(v, str):
            errs.append({"type": "string_type", "loc": ["body", f],
                         "msg": "Input should be a valid string", "input": v})
    page, size = body.get("page", 1), body.get("page_size", 20)
    if not isinstance(page, int) or isinstance(page, bool):
        errs.append({"type": "int_type", "loc": ["body", "page"],
                     "msg": "Input should be a valid integer", "input": page})
    elif page < 1:
        errs.append({"type": "greater_than_equal", "loc": ["body", "page"],
                     "msg": "Input should be greater than or equal to 1", "input": page})
    if not isinstance(size, int) or isinstance(size, bool):
        errs.append({"type": "int_type", "loc": ["body", "page_size"],
                     "msg": "Input should be a valid integer", "input": size})
    elif size < 1:
        errs.append({"type": "greater_than_equal", "loc": ["body", "page_size"],
                     "msg": "Input should be greater than or equal to 1", "input": size})
    elif size > 100:
        errs.append({"type": "less_than_equal", "loc": ["body", "page_size"],
                     "msg": "Input should be less than or equal to 100", "input": size})
    if errs:
        raise ApiError(422, errs)


def search_students(body, **_):
    _validate_search_body(body)
    rows = STUDENTS
    if body.get("term"):
        rows = [s for s in rows if s["term"] == body["term"]]
    if body.get("college"):
        needle = body["college"].lower()
        rows = [s for s in rows if s["college"] and needle in s["college"].lower()]
    for c in body.get("career_interests", []):  # AND
        if c in CAREER_COLUMNS:
            rows = [s for s in rows if c in s["career_interests"]]
    for e in body.get("experience_preferences", []):  # AND
        rows = [s for s in rows if e in s["experience_preferences"]]
    doms = body.get("research_domains", [])
    if doms:  # OR
        rows = [s for s in rows if any(d in s["research_domains"] for d in doms)]
    rows = sorted(rows, key=lambda s: (-(s["term_year"] or 0), s["student_id"]))
    page, size = body.get("page", 1), body.get("page_size", 20)
    return {"students": _paginate(rows, page, size), "total": len(rows), "page": page, "page_size": size}


# ------------------------------------------------------------------- extension: academics
def student_courses(student_id, **_):
    if not any(s["student_id"] == student_id for s in STUDENTS):
        raise ApiError(404, "Student not found")
    by_code = {c["code"]: c for c in COURSES}
    out = []
    for t in ENROLLMENTS.get(student_id, []):
        y, se = _term_info(t["term"])
        out.append({"term": t["term"], "term_year": y, "term_season": se,
                    "courses": [{"code": c, "subject": by_code[c]["subject"],
                                 "catalog_nbr": by_code[c]["catalog_nbr"],
                                 "department_id": by_code[c]["department_id"]}
                                for c in t["courses"] if c in by_code]})
    return {"student_id": student_id, "terms": out}


def _term_info(term):
    return 2000 + int(term[1:]), "Fall" if term[0] == "F" else "Spring"


def list_courses(query, **_):
    page, size = _page_args(query)
    rows = COURSES
    if query.get("subject"):
        rows = [c for c in rows if c["subject"].lower() == query["subject"].lower()]
    if query.get("q"):
        rows = [c for c in rows if query["q"].lower() in c["code"].lower()]
    if query.get("department_id"):
        rows = [c for c in rows if c["department_id"] == query["department_id"]]
    return {"courses": _paginate(rows, page, size), "total": len(rows), "page": page, "page_size": size}


def list_departments(query, **_):
    rows = DEPARTMENTS
    if query.get("has_courses", "").lower() in ("1", "true"):
        rows = [d for d in rows if d["has_courses"]]
    if query.get("q"):
        rows = [d for d in rows if query["q"].lower() in d["name"].lower()]
    return {"departments": rows, "total": len(rows)}


def list_programs(query, **_):
    page, size = _page_args(query)
    rows = PROGRAMS
    if query.get("type"):
        rows = [p for p in rows if (p["program_type"] or "").lower() == query["type"].lower()]
    if query.get("q"):
        n = query["q"].lower()
        rows = [p for p in rows if n in p["name"].lower() or n in (p["description"] or "").lower()]
    return {"programs": _paginate(rows, page, size), "total": len(rows), "page": page, "page_size": size}


def get_program(program_id, **_):
    for p in PROGRAMS:
        if p["id"] == program_id:
            return p
    raise ApiError(404, "Program not found")


# --------------------------------------------------------------------- extension: faculty
def _faculty_summary(f):
    return {k: f[k] for k in ("faculty_id", "name", "title", "primary_department", "college",
                              "research_interests", "offering_opportunities", "opportunity_types",
                              "majors_considered", "research_locations")} | {"project": f["project"]}


def list_faculty(query, **_):
    page, size = _page_args(query)
    rows = FACULTY
    if query.get("q"):
        n = query["q"].lower()
        rows = [f for f in rows if n in " ".join([f["name"] or "", f["primary_department"] or "",
                                                  " ".join(f["research_interests"])]).lower()]
    if query.get("department"):
        rows = [f for f in rows if (f["primary_department"] or "").lower() == query["department"].lower()]
    if query.get("college"):
        rows = [f for f in rows if query["college"].lower() in (f["college"] or "").lower()]
    if query.get("type"):
        rows = [f for f in rows if query["type"].lower() in [t.lower() for t in f["opportunity_types"]]]
    if query.get("status"):
        rows = [f for f in rows if f["project"] and f["project"]["application_status"] == query["status"]]
    return {"faculty": [_faculty_summary(f) for f in _paginate(rows, page, size)],
            "total": len(rows), "page": page, "page_size": size}


def get_faculty(faculty_id, **_):
    f = FACULTY_BY_ID.get(faculty_id)
    if not f:
        raise ApiError(404, "Faculty not found")
    return f


# ------------------------------------------------------------------------------ matching
DOMAIN_KEYWORDS = {
    "healthcare_medicine": {"health", "medic", "bio", "neuro", "nurs", "cancer", "clinical", "physiol", "pharm"},
    "engineering": {"engineer", "material", "optic", "mining", "aerospace", "mechanic", "electrical", "robot"},
    "data_science_statistics": {"data", "comput", "statist", "machine", "inform", "algorithm", "software"},
    "arts_humanities": {"art", "humanit", "english", "music", "literat", "philosoph", "history", "writing"},
    "business_economics": {"business", "econom", "manage", "financ", "market", "account"},
    "education_pedagogy": {"educ", "learning", "teaching", "pedagog", "curricul"},
    "environment_sustainability": {"environment", "ecolog", "sustain", "plant", "climate", "water", "conserv"},
    "social_behavioral_sciences": {"psych", "social", "behavior", "sociol", "anthrop", "cogni", "communic"},
    "law_policy": {"law", "policy", "politic", "govern", "justice", "public"},
}
STOP = {"and", "of", "the", "in", "related", "for", "a", "studies", "science", "sciences",
        "management", "administration", "general", "applied"}


def _words(text):
    return {w for w in re.findall(r"[a-z]+", (text or "").lower()) if w not in STOP and len(w) > 2}


def _major_score(plan, majors):
    """0..1 plus a reason string."""
    if not plan:
        return 0.0, None
    p = plan.lower()
    pw = _words(plan)
    best, why = 0.0, None
    for m in majors:
        m = re.sub(r"^(and|or)\s+", "", m.strip(), flags=re.I)
        ml = re.sub(r"\(.*?\)", "", m).strip().lower()
        if ml in ("any", "all", "not given", ""):
            if best < 0.45:
                best, why = 0.45, "Open to students from any major"
            continue
        if p == ml:
            return 1.0, f"Your plan ({plan}) is one of the majors this researcher considers"
        mw = _words(ml)
        if len(ml.split()) > 5:  # run-together free text typed by the researcher; don't quote it
            if pw and (p in ml or pw <= mw) and best < 0.7:
                best, why = 0.7, f"Your plan ({plan}) appears in the majors this researcher listed"
            continue
        if pw and mw and (pw <= mw or mw <= pw):
            if best < 0.8:
                best, why = 0.8, f"Your plan ({plan}) is closely related to {m}"
        elif pw & mw and best < 0.5:
            best, why = 0.5, f"Your plan ({plan}) overlaps with {m}"
    return best, why


def score_match(student, f, prefs):
    p = f["project"]
    blob = " ".join([f["primary_department"] or "", f["college"] or "", " ".join(f["research_interests"]),
                     " ".join(f["majors_considered"]), p["title"]]).lower()
    reasons = []
    major, why = _major_score(student.get("plan"), f["majors_considered"])
    if why:
        reasons.append(why)
    hit_domains = [d for d in student.get("research_domains", [])
                   if any(k in blob for k in DOMAIN_KEYWORDS.get(d, ()))]
    dom = min(1.0, len(hit_domains) / 2) if student.get("research_domains") else 0.0
    if hit_domains:
        reasons.append("Your interests (" + ", ".join(d.replace("_", " ") for d in hit_domains)
                       + ") line up with this lab's area")
    plan_dept = 0.0
    if _words(student.get("plan")) & _words(f["primary_department"] or ""):
        plan_dept = 1.0
        reasons.append(f"Your plan relates to the {f['primary_department']} department")
    exp = student.get("experience_preferences", [])
    research_signal = bool({"exp_facresearch", "exp_empresearch"} & set(exp)) or \
        "career_research" in student.get("career_interests", [])
    expfit = 1.0 if research_signal else 0.3
    if research_signal:
        reasons.append("You said you're interested in faculty research experience")
    types = {t.lower() for t in f["opportunity_types"]}
    if prefs.get("paid") and "paid" in types:
        expfit = min(1.0, expfit + .3); reasons.append("Offers paid positions, as you prefer")
    if prefs.get("for_credit") and "for credit" in types:
        expfit = min(1.0, expfit + .3); reasons.append("Offers academic credit, as you prefer")
    if prefs.get("volunteer") and "volunteer" in types:
        expfit = min(1.0, expfit + .3); reasons.append("Offers volunteer positions, as you prefer")
    avail = {"open": 1.0, "rolling": 0.9, "not_yet_open": 0.5, "closed": 0.1}[p["application_status"]]
    raw = 0.40 * major + 0.25 * dom + 0.10 * plan_dept + 0.15 * expfit + 0.10 * avail
    pct = max(30, min(98, round(30 + 68 * raw / 0.85)))
    return pct, reasons, {"major": round(major, 2), "domains": round(dom, 2), "department": plan_dept,
                          "experience": round(expfit, 2), "availability": avail}


def post_matches(body, **_):
    if not isinstance(body, dict) or not isinstance(body.get("student"), dict):
        raise ApiError(422, [{"type": "missing", "loc": ["body", "student"],
                              "msg": "Field required (an NSIF student record)", "input": body}])
    student = body["student"]
    prefs = body.get("preferences") or {}
    limit = body.get("limit", 10)
    if not isinstance(limit, int) or isinstance(limit, bool) or not 1 <= limit <= 100:
        raise ApiError(422, [{"type": "int_range", "loc": ["body", "limit"],
                              "msg": "limit must be an integer between 1 and 100", "input": limit}])
    include_closed = bool(prefs.get("include_closed"))
    cands = [f for f in FACULTY if f["offering_opportunities"] and f["project"]
             and (include_closed or f["project"]["application_status"] != "closed")]
    scored = []
    for f in cands:
        pct, reasons, signals = score_match(student, f, prefs)
        scored.append((pct, f["name"] or "", f, reasons, signals))
    scored.sort(key=lambda t: (-t[0], t[1]))
    matches = [{"faculty": _faculty_summary(f), "match": {"percent": pct, "reasons": reasons, "signals": sig}}
               for pct, _, f, reasons, sig in scored[:limit]]
    return {"student_id": student.get("student_id"), "matches": matches, "total_candidates": len(cands),
            "meta": {"heuristic": True, "note": "Mock heuristic (plan, interest-domain and preference "
                     "overlap). Not the production recommender. Projects are synthetic."}}


